 fireEvent.click(screen.getByRole('button',{name:'Guardar'}))
 await waitFor(()=>expect(saved).toHaveBeenCalled())
 const result=(savePlan as jest.Mock).mock.calls.at(-1)[1]
 expect(result.tables[0]).toMatchObject({x:0,y:0})
