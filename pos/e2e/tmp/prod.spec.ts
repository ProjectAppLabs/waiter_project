import { USERS, expect, signIn, test } from '../helpers/waiter'
test('producción sin red', async ({ page, context }) => {
  await signIn(page, USERS.manager)
  await page.waitForURL(/dashboard|caja|salon/)
  for (const p of ['/pedidos', '/pedidos/nuevo', '/emergencia', '/salon']) { await page.goto(p); await page.waitForTimeout(2500) }
  console.log('sw', await page.evaluate(async () => (await navigator.serviceWorker.getRegistrations()).map((r) => r.active?.state)))
  console.log('cache', await page.evaluate(async () => { const c = await caches.open('waiter-app-v1'); return (await c.keys()).map((r) => new URL(r.url).pathname).slice(0, 40) }))
  await context.setOffline(true)
  await page.goto('/pedidos').catch((e) => console.log('goto pedidos', String(e).slice(0, 120)))
  await page.waitForTimeout(3000)
  console.log('pedidos offline:', (await page.locator('body').innerText()).slice(0, 300).replace(/\n/g, ' | '))
  await page.getByRole('link', { name: 'Mesas' }).click().catch((e) => console.log('click mesas', String(e).slice(0, 100)))
  await page.waitForTimeout(3000)
  console.log('url', page.url(), (await page.locator('body').innerText()).slice(0, 200).replace(/\n/g, ' | '))
  await page.goto('/emergencia').catch((e) => console.log('goto emergencia', String(e).slice(0, 120)))
  await page.waitForTimeout(3000)
  console.log('emergencia offline:', page.url(), (await page.locator('body').innerText()).slice(0, 300).replace(/\n/g, ' | '))
  await context.setOffline(false)
  expect(1).toBe(1)
})
