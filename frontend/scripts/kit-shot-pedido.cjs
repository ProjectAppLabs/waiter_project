// Capturas del wizard "Crear pedido" y del modal de pago a 1194×834, en claro y en oscuro, para cotejarlas
// con docs/diseno/pos-kit/pantallas/Visual Design Light/{5 – Create New Order, 9 – Payment}.
// Uso: PLAYWRIGHT_BASE_URL=http://192.168.56.10:3012 node scripts/kit-shot-pedido.cjs [light|dark]
const { chromium, devices } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')

const base = process.env.PLAYWRIGHT_BASE_URL || 'http://localhost:3000'
const theme = process.argv[2] === 'dark' ? 'dark' : 'light'
const out = path.join(__dirname, '..', 'kit-compare', `pedido-${theme}`)

async function main() {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch()
  const context = await browser.newContext({ ...devices['iPad Pro 11 landscape'] })
  await context.addInitScript((mode) => { try { localStorage.setItem('waiter.theme', mode) } catch { /* sin almacenamiento */ } }, theme)
  const page = await context.newPage()
  page.setDefaultTimeout(60_000)
  page.setDefaultNavigationTimeout(120_000)
  let n = 0
  const shot = async (name) => { await page.waitForTimeout(600); await page.screenshot({ path: path.join(out, `${String(++n).padStart(2, '0')}-${name}.png`) }); console.log(name) }

  await page.goto(`${base}/login`)
  await page.waitForLoadState('networkidle')
  await page.waitForTimeout(1500)
  await page.getByLabel('Correo').fill('admin')
  await page.getByLabel('Contraseña').fill('admin')
  await page.getByRole('button', { name: 'Abrir mi turno' }).click()
  await page.waitForURL('**/salon')

  // 1 · En mesa: información del cliente → mesa → menú → resumen
  await page.goto(`${base}/pedidos/nuevo`)
  await page.waitForLoadState('networkidle')
  await shot('customer-dinein')
  await page.getByLabel('Nombre del cliente').fill('Kit A1AC')
  await page.getByRole('button', { name: 'Continuar' }).click()
  await shot('select-table')
  const table = page.locator('button[aria-pressed="false"]:not([disabled])').filter({ hasText: 'Mesa' }).first()
  await table.click()
  await shot('table-selected')
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForTimeout(1200)
  await shot('menu-empty')
  await page.getByPlaceholder('Buscar plato').fill('Hamburguesa')
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Agregar', exact: true }).first().click()
  await shot('add-dish')
  const required = page.getByRole('radio')
  if (await required.count()) await required.first().click()
  await page.getByLabel('Nota para cocina').fill('sin cebolla')
  await page.getByRole('button', { name: /Agregar al carrito/ }).click()
  await page.getByPlaceholder('Buscar plato').fill('')
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Agregar', exact: true }).nth(1).click()
  const required2 = page.getByRole('radio')
  if (await required2.count()) await required2.first().click()
  await page.getByRole('button', { name: /Agregar al carrito/ }).click()
  await shot('menu-filled')
  await page.locator('section[aria-label="Detalle del pedido"]').getByRole('button', { name: 'Continuar' }).click()
  await shot('summary-dinein')

  // 2 · Para llevar: resumen con "Continuar al pago" y el modal de pago del kit
  await page.goto(`${base}/pedidos/nuevo`)
  await page.waitForLoadState('networkidle')
  await page.getByRole('radio', { name: 'Para llevar' }).click()
  await page.getByLabel('Nombre del cliente').fill('Kit A1AC llevar')
  await shot('customer-takeaway')
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.waitForTimeout(1200)
  await page.getByRole('button', { name: 'Agregar', exact: true }).first().click()
  const req3 = page.getByRole('radio')
  if (await req3.count()) await req3.first().click()
  await page.getByRole('button', { name: /Agregar al carrito/ }).click()
  await page.locator('section[aria-label="Detalle del pedido"]').getByRole('button', { name: 'Continuar' }).click()
  await shot('summary-takeaway')
  await page.getByRole('button', { name: 'Continuar al pago' }).click()
  await page.getByRole('dialog', { name: 'Pago' }).waitFor()
  await page.getByRole('button', { name: 'Pagar ahora' }).waitFor()
  await shot('payment-cash')
  await page.getByLabel('Código de socio').fill('KITA1AC001')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await page.waitForTimeout(2000)
  await shot('payment-member')
  await page.getByRole('switch', { name: '¿Usar puntos?' }).click()
  await page.getByRole('tab', { name: 'Tarjeta' }).click()
  await shot('payment-card')
  await page.getByRole('button', { name: 'Confirmar pago' }).click()
  await shot('payment-edc')
  await page.getByRole('tab', { name: 'Código QR' }).click()
  await shot('payment-qr')
  await page.getByRole('button', { name: 'Más opciones' }).click()
  await shot('payment-options')
  await page.getByRole('button', { name: 'Más opciones' }).click()
  await page.getByRole('tab', { name: 'Efectivo' }).click()
  await page.getByRole('button', { name: '100.000' }).click()
  await page.getByRole('button', { name: 'Pagar ahora' }).click()
  try { await page.getByRole('dialog', { name: '¡Pago exitoso!' }).waitFor({ timeout: 60_000 }) } catch { await shot('payment-failed') }
  await shot('payment-success')

  await browser.close()
}
main().catch((e) => { console.error(e); process.exit(1) })
