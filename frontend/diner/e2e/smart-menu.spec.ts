// Falla si la carta se desborda a lo ancho en móvil, tablet o escritorio, o si la vista previa escribe en la API.
test('Smart Menu se adapta a móvil, tablet y escritorio; la vista previa no escribe pedidos', async ({ page }) => {
  test.setTimeout(120_000)
  const mutations: string[] = []
  page.on('request', (r) => { if (r.method() !== 'GET' && r.url().includes('/api/v1/')) mutations.push(r.url()) })
  const preview = Buffer.from(JSON.stringify({ plantilla: 'S1', paleta: { acento: '#145A52', tintaTerciaria: '#F3C673' }, tipografia: { display: 'DM Sans' } })).toString('base64url')
  await page.goto(`${base}/carta/?vista_previa=${preview}`)
  await expect(page.getByText('Vista previa · cambios sin guardar')).toBeVisible()
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.locator('.sm-food-card').first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.screenshot({ path: `/tmp/fig-review/menu-${width}.png` })
  }
  await page.locator('.sm-food-link').nth(1).click()
  await page.getByRole('button', { name: /Agregar a mi pedido/ }).click()
  await expect(page.locator('.sm-error')).toContainText('vista previa')
  expect(mutations).toEqual([])
})
